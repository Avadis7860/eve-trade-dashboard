/**
 * Phase P02 — Registre Minier & Coûts d'Opportunité Farm / Mining
 * Modèles de domaine, statuts de provenance et contrats stricts
 */

export type FarmedProvenance = 'FARMED';

export type MiningValuationStatus = 'KNOWN' | 'PARTIAL' | 'UNKNOWN';

export interface MiningLedgerEntry {
  id?: number;
  characterId: number;
  date: string; // YYYY-MM-DD
  solarSystemId: number;
  solarSystemName?: string;
  typeId: number;
  typeName?: string;
  quantity: number;
  estimatedUnitValue: number | null; // null si inconnu, JAMAIS coercé silencieusement à 0.00
  opportunityCostIsk: number | null; // quantity * estimatedUnitValue, null si estimatedUnitValue est null
  realizedCashCostIsk: 0; // Invariance stricte : sortie de trésorerie nulle (0.00 ISK)
  provenance: FarmedProvenance;
  costBasisStatus: 'KNOWN' | 'UNKNOWN';
  createdAt?: number;
}

export interface MiningOpportunityReference {
  typeId: number;
  typeName?: string;
  referencePrice: number;
  source: 'HUB_AVERAGE' | 'ESI_ESTIMATED' | 'USER_OVERRIDE' | 'FALLBACK_MINERAL_VALUE';
  updatedAt: number;
}

export interface MiningLedgerFilterOptions {
  characterId?: number;
  characterIds?: number[];
  solarSystemId?: number;
  typeId?: number;
  startDate?: string;
  endDate?: string;
  limit?: number;
  offset?: number;
}

export interface MiningTypeBreakdown {
  typeId: number;
  typeName?: string;
  quantity: number;
  estimatedUnitValue: number | null;
  opportunityCostIsk: number | null;
  valuationStatus: 'KNOWN' | 'UNKNOWN';
  percentageOfTotalQuantity: number;
}

export interface MiningSolarSystemBreakdown {
  solarSystemId: number;
  solarSystemName?: string;
  quantity: number;
  opportunityCostIsk: number | null;
}

export interface MiningCharacterBreakdown {
  characterId: number;
  characterName?: string;
  quantity: number;
  opportunityCostIsk: number | null;
}

export interface MiningLedgerSummary {
  totalQuantity: number;
  totalEntries: number;
  activeDaysCount: number;
  totalOpportunityCostIsk: number | null;
  valuationStatus: MiningValuationStatus;
  knownValueQuantity: number;
  unknownValueQuantity: number;
  uniqueTypesCount: number;
  uniqueSolarSystemsCount: number;
  byType: MiningTypeBreakdown[];
  bySolarSystem: MiningSolarSystemBreakdown[];
  byCharacter: MiningCharacterBreakdown[];
  asOf: number;
}

export interface FarmDualProfitability {
  typeId: number;
  typeName?: string;
  quantity: number;
  salePriceIsk: number;
  taxesIsk: number;
  // 1. Pure commercial ROI based on opportunity cost
  opportunityCostIsk: number | null;
  commercialProfitIsk: number | null; // salePriceIsk - opportunityCostIsk - taxesIsk (null si opportunité inconnue)
  commercialRoiPercent: number | null; // (commercialProfitIsk / opportunityCostIsk) * 100 (null si <= 0 ou opportunité inconnue)
  // 2. Global farming gross cash margin generated by player gameplay time
  realizedCashCostIsk: 0;
  cashMarginIsk: number; // salePriceIsk - taxesIsk
  cashMarginPercent: 100; // 100% car aucun décaissement de trésorerie
  valuationStatus: 'KNOWN' | 'UNKNOWN';
}
